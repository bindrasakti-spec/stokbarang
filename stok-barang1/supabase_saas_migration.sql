-- 1. Tabel Workspaces (Multi-Tenant Isolation)
CREATE TABLE IF NOT EXISTS public.workspaces (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  owner_user_id BIGINT,
  owner_email TEXT DEFAULT '',
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Tambahkan kolom workspace_id & email ke tabel existing tanpa menghapus data lama
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS workspace_id BIGINT NOT NULL DEFAULT 1;
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS email TEXT DEFAULT '';
ALTER TABLE public.items ADD COLUMN IF NOT EXISTS workspace_id BIGINT NOT NULL DEFAULT 1;
ALTER TABLE public.transactions ADD COLUMN IF NOT EXISTS workspace_id BIGINT NOT NULL DEFAULT 1;

-- 2. Tabel Paket Berlangganan (Harga & Kuota Dinamis dari Database)
CREATE TABLE IF NOT EXISTS public.subscription_plans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT UNIQUE NOT NULL,
  name TEXT NOT NULL,
  target_audience TEXT DEFAULT '',
  description TEXT DEFAULT '',
  price_monthly DOUBLE PRECISION NOT NULL DEFAULT 0,
  price_yearly DOUBLE PRECISION NOT NULL DEFAULT 0,
  max_warehouses INTEGER NOT NULL DEFAULT 1,
  max_users INTEGER NOT NULL DEFAULT 3,
  features JSONB NOT NULL DEFAULT '[]'::jsonb,
  is_recommended BOOLEAN NOT NULL DEFAULT FALSE,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Tabel Langganan Workspace (Subscriptions)
CREATE TABLE IF NOT EXISTS public.workspace_subscriptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT UNIQUE NOT NULL REFERENCES public.workspaces(id) ON DELETE CASCADE,
  plan_id BIGINT REFERENCES public.subscription_plans(id),
  status TEXT NOT NULL DEFAULT 'TRIAL' CHECK (status IN ('TRIAL', 'ACTIVE', 'PAST_DUE', 'EXPIRED', 'CANCELLED')),
  billing_cycle TEXT NOT NULL DEFAULT 'trial' CHECK (billing_cycle IN ('trial', 'monthly', 'yearly')),
  trial_started_at TIMESTAMPTZ,
  trial_ends_at TIMESTAMPTZ,
  current_period_start TIMESTAMPTZ,
  current_period_end TIMESTAMPTZ,
  warehouses_used INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- View/Alias kompatibilitas jika ada query ke subscriptions
CREATE TABLE IF NOT EXISTS public.subscriptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL REFERENCES public.workspaces(id) ON DELETE CASCADE,
  plan_id BIGINT REFERENCES public.subscription_plans(id),
  status TEXT NOT NULL DEFAULT 'TRIAL',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. Tabel Pembayaran Langganan
CREATE TABLE IF NOT EXISTS public.subscription_payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL REFERENCES public.workspaces(id) ON DELETE CASCADE,
  subscription_id BIGINT REFERENCES public.workspace_subscriptions(id) ON DELETE SET NULL,
  plan_id BIGINT REFERENCES public.subscription_plans(id) ON DELETE SET NULL,
  order_id TEXT UNIQUE NOT NULL,
  amount DOUBLE PRECISION NOT NULL DEFAULT 0,
  billing_cycle TEXT NOT NULL DEFAULT 'monthly' CHECK (billing_cycle IN ('monthly', 'yearly')),
  payment_method TEXT NOT NULL DEFAULT 'manual_transfer' CHECK (payment_method IN ('manual_transfer', 'midtrans', 'xendit')),
  payment_gateway_ref TEXT DEFAULT '',
  proof_note TEXT DEFAULT '',
  status TEXT NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'PAID', 'FAILED', 'EXPIRED', 'REFUNDED')),
  verified_by TEXT DEFAULT '',
  verified_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. Tabel Invoice Langganan
CREATE TABLE IF NOT EXISTS public.subscription_invoices (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_number TEXT UNIQUE NOT NULL,
  workspace_id BIGINT NOT NULL REFERENCES public.workspaces(id) ON DELETE CASCADE,
  payment_id BIGINT REFERENCES public.subscription_payments(id) ON DELETE CASCADE,
  plan_name TEXT NOT NULL,
  billing_cycle TEXT NOT NULL DEFAULT 'monthly',
  amount DOUBLE PRECISION NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'PAID', 'FAILED', 'EXPIRED', 'REFUNDED')),
  issued_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  paid_at TIMESTAMPTZ
);

-- 6. Tabel Platform Super Admins (Pemilik SaaS)
CREATE TABLE IF NOT EXISTS public.platform_admins (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT UNIQUE,
  username TEXT UNIQUE NOT NULL,
  email TEXT DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 7. Tabel Audit Log Perubahan Subscription
CREATE TABLE IF NOT EXISTS public.subscription_audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL,
  actor_user_id BIGINT,
  actor_username TEXT NOT NULL DEFAULT 'system',
  action TEXT NOT NULL,
  old_status TEXT DEFAULT '',
  new_status TEXT DEFAULT '',
  old_plan_code TEXT DEFAULT '',
  new_plan_code TEXT DEFAULT '',
  notes TEXT DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

