-- (Aman dijalankan ulang karena menggunakan IF NOT EXISTS & ON CONFLICT DO NOTHING)

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  full_name TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'teknisi' CHECK (role IN ('superadmin', 'admin', 'teknisi', 'spesial', 'viewer')),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku TEXT UNIQUE NOT NULL,
  name TEXT NOT NULL,
  category TEXT NOT NULL,
  unit TEXT NOT NULL DEFAULT 'Pcs',
  min_stock INTEGER NOT NULL DEFAULT 5,
  price DOUBLE PRECISION NOT NULL DEFAULT 0,
  initial_stock INTEGER NOT NULL DEFAULT 0,
  current_stock INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id BIGINT NOT NULL REFERENCES items(id) ON DELETE CASCADE,
  type TEXT NOT NULL CHECK (type IN ('IN', 'OUT')),
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  reason TEXT NOT NULL,
  date TEXT NOT NULL,
  notes TEXT DEFAULT '',
  sell_price DOUBLE PRECISION NOT NULL DEFAULT 0,
  total_sell_price DOUBLE PRECISION NOT NULL DEFAULT 0,
  user_id BIGINT NOT NULL REFERENCES users(id),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS folder_settings (
  company TEXT PRIMARY KEY CHECK (company IN ('GMDP', 'GENAP')),
  base_customers INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS folder_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company TEXT NOT NULL CHECK (company IN ('GMDP', 'GENAP')),
  type TEXT NOT NULL CHECK (type IN ('IN', 'OUT')),
  count INTEGER NOT NULL DEFAULT 1 CHECK (count > 0),
  category TEXT NOT NULL,
  customer_info TEXT DEFAULT '',
  date TEXT NOT NULL,
  user_name TEXT DEFAULT 'Petugas',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS folder_monthly_manual (
  company TEXT NOT NULL CHECK (company IN ('GMDP', 'GENAP')),
  month TEXT NOT NULL,
  manual_opening INTEGER,
  manual_in INTEGER NOT NULL DEFAULT 0,
  manual_out INTEGER NOT NULL DEFAULT 0,
  notes TEXT DEFAULT '',
  PRIMARY KEY (company, month)
);

CREATE TABLE IF NOT EXISTS folder_deleted_months (
  company TEXT NOT NULL CHECK (company IN ('GMDP', 'GENAP')),
  month TEXT NOT NULL,
  PRIMARY KEY (company, month)
);

CREATE TABLE IF NOT EXISTS folder_yearly_manual (
  company TEXT NOT NULL CHECK (company IN ('GMDP', 'GENAP')),
  year TEXT NOT NULL,
  manual_opening INTEGER,
  manual_in INTEGER,
  manual_out INTEGER,
  notes TEXT DEFAULT '',
  PRIMARY KEY (company, year)
);

CREATE TABLE IF NOT EXISTS folder_deleted_years (
  company TEXT NOT NULL CHECK (company IN ('GMDP', 'GENAP')),
  year TEXT NOT NULL,
  PRIMARY KEY (company, year)
);

CREATE TABLE IF NOT EXISTS activity_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT,
  username TEXT NOT NULL,
  full_name TEXT NOT NULL,
  role TEXT NOT NULL,
  action_type TEXT NOT NULL CHECK (action_type IN ('LOGIN', 'EDIT', 'EXPORT')),
  target TEXT NOT NULL DEFAULT '',
  detail TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Seed default settings folder pelanggan
INSERT INTO folder_settings (company, base_customers)
VALUES ('GMDP', 0), ('GENAP', 0)
ON CONFLICT (company) DO NOTHING;

-- ==================== KEAMANAN RLS & GRANT SERVICE_ROLE ====================
-- Mengaktifkan RLS agar tabel tidak bisa diakses langsung dari client/anon key,
-- sekaligus memastikan backend (role service_role) memiliki izin penuh.
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.transactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.folder_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.folder_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.folder_monthly_manual ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.folder_deleted_months ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.folder_yearly_manual ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.folder_deleted_years ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.activity_logs ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.users FROM anon, authenticated;
REVOKE ALL ON TABLE public.activity_logs FROM anon, authenticated;

GRANT USAGE ON SCHEMA public TO service_role;
GRANT ALL ON TABLE
  public.users,
  public.items,
  public.transactions,
  public.folder_settings,
  public.folder_logs,
  public.folder_monthly_manual,
  public.folder_deleted_months,
  public.folder_yearly_manual,
  public.folder_deleted_years,
  public.activity_logs
TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;

